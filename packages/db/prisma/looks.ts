/**
 * The feed's sample looks and the pieces in them.
 *
 * Each look is one outfit laid out or hung up the way good sellers photograph
 * clothes, and every piece listed here is the garment actually in that photo.
 * Nothing is "in the spirit of" anything: tap a line in the credit list and
 * you get the thing you were looking at.
 *
 * The images are generated samples, made to be replaced by real posts. See
 * seed-assets/looks and seed-assets/pieces. `scene` and `brief` are the words
 * they were generated from, kept so a set can be remade.
 */

export type SeedSlot =
  | 'TOP'
  | 'BOTTOM'
  | 'FULL_BODY'
  | 'OUTERWEAR'
  | 'SHOES'
  | 'BAG'
  | 'JEWELLERY'
  | 'EYEWEAR'
  | 'HEADWEAR';

export interface SeedPiece {
  slug: string;
  title: string;
  slot: SeedSlot;
  price: number;
  colours: string[];
  sizes: string[];
  description: string;
  /** What the garment looks like, for the image. */
  brief: string;
}

